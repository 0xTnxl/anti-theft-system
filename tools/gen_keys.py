#!/usr/bin/env python3
"""Generate include/secrets.h: the pre-shared key and MAC addresses for one
exterior/interior pair.

Both boards must be flashed with the SAME secrets.h. Regenerating it un-pairs
any boards already flashed, so the script refuses to overwrite without --force.

MAC addresses are random, locally administered unicast addresses. The firmware
sets them as the ESP32 base MAC at boot, so the real factory MACs do not need
to be read off the boards.
"""
import argparse
import os
import secrets
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_OUT = os.path.join(HERE, "..", "include", "secrets.h")


def random_mac() -> bytes:
    mac = bytearray(secrets.token_bytes(6))
    mac[0] = (mac[0] & 0xFC) | 0x02  # unicast, locally administered
    return bytes(mac)


def c_array(data: bytes) -> str:
    return ", ".join(f"0x{b:02X}" for b in data)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", default=DEFAULT_OUT, help="output header path")
    ap.add_argument("--force", action="store_true", help="overwrite an existing file")
    args = ap.parse_args()

    out = os.path.abspath(args.out)
    if os.path.exists(out) and not args.force:
        print(f"{out} already exists. Use --force to replace it "
              "(boards flashed with the old file will stop pairing).", file=sys.stderr)
        return 1

    psk = secrets.token_bytes(32)
    mac_e = random_mac()
    mac_i = random_mac()
    while mac_i == mac_e:
        mac_i = random_mac()

    text = f"""// GENERATED by tools/gen_keys.py. Do not commit. Do not edit by hand.
#pragma once
#include <stdint.h>

#define ATDS_SECRETS_VERSION 1

// 256-bit pre-shared pairing key (authenticates the handshake, salts HKDF).
static const uint8_t ATDS_PSK[32] = {{
    {c_array(psk[:16])},
    {c_array(psk[16:])}}};

// Base MAC addresses forced at boot. ESP-NOW frames from any other MAC are dropped.
static const uint8_t ATDS_MAC_EXTERIOR[6] = {{{c_array(mac_e)}}};
static const uint8_t ATDS_MAC_INTERIOR[6] = {{{c_array(mac_i)}}};
"""
    os.makedirs(os.path.dirname(out), exist_ok=True)
    fd = os.open(out, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write(text)
    print(f"Wrote {out}")
    print(f"  exterior MAC {mac_e.hex(':')}")
    print(f"  interior MAC {mac_i.hex(':')}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
